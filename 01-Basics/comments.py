# ==========================================
# Python Comments
# ==========================================


# ------------------------------------------
# 1. Single-line comments
# ------------------------------------------

# This is a comment
name = "Chris"

print(name)  # This is also a comment


# ------------------------------------------
# 2. Comments explaining code
# ------------------------------------------

age = 18

# Add one year to the age
next_year = age + 1

print(next_year)


# ------------------------------------------
# 3. Multi-line comments
# ------------------------------------------

"""
This is a multi-line comment.
You can write multiple lines here.
Python will treat this as a string
when it isn't assigned to anything.
"""

print("Hello Python")


