# ==========================================
# Python range()
# ==========================================


# ------------------------------------------
# 1. Basic range()
# ------------------------------------------

for i in range(5):
    print(i)


# ------------------------------------------
# 2. range(start, stop)
# ------------------------------------------

for i in range(1, 6):
    print(i)


# ------------------------------------------
# 3. range(start, stop, step)
# ------------------------------------------

for i in range(1, 11, 2):
    print(i)


# ------------------------------------------
# 4. Even Numbers
# ------------------------------------------

for i in range(2, 21, 2):
    print(i)


# ------------------------------------------
# 5. Counting Backwards
# ------------------------------------------

for i in range(10, 0, -1):
    print(i)


# ------------------------------------------
# 6. Negative Numbers
# ------------------------------------------

for i in range(-5, 1):
    print(i)


# ------------------------------------------
# 7. Using range() with a List
# ------------------------------------------

languages = ["Python", "C++", "Java"]

for i in range(len(languages)):
    print(i, languages[i])


# ------------------------------------------
# 8. Convert range() to a List
# ------------------------------------------

numbers = list(range(1, 11))

print(numbers)


# ------------------------------------------
# 9. Sum of Numbers
# ------------------------------------------

total = 0

for i in range(1, 101):
    total += i

print("Sum:", total)


# ------------------------------------------
# 10. Multiplication Table
# ------------------------------------------

number = int(input("Enter a number: "))

for i in range(1, 11):
    print(number, "x", i, "=", number * i)
