# ------------------------------------------
# 1. Creating a Function
# ------------------------------------------

def greet():
    print("Hello!")


greet()


# ------------------------------------------
# 2. Calling a Function Multiple Times
# ------------------------------------------

def say_hello():
    print("Hello, welcome to Python!")


say_hello()
say_hello()
say_hello()


# ------------------------------------------
# 3. Function with Multiple Statements
# ------------------------------------------

def introduction():
    print("My name is Chris")
    print("I am learning Python")
    print("I want to become a developer")


introduction()


# ------------------------------------------
# 4. Functions Help Reuse Code
# ------------------------------------------

def line():
    print("--------------------")


line()
print("Python")
line()
print("Functions")
line()


# ------------------------------------------
# 5. Function Naming
# ------------------------------------------

def calculate():
    print("Calculation started")


calculate()


# ------------------------------------------
# 6. A Function Can Call Another Function
# ------------------------------------------

def hello():
    print("Hello")


def goodbye():
    print("Goodbye")


hello()
goodbye()


# ------------------------------------------
# 7. Function with Local Variables
# ------------------------------------------

def show_number():
    number = 10
    print(number)


show_number()


